from diysca import db


def test_to_pg():
    assert db.to_pg("SELECT * FROM t WHERE a LIKE ? AND b='5%' AND c=?") == \
        "SELECT * FROM t WHERE a ILIKE %s AND b='5%%' AND c=%s"


def test_pg_schema_types():
    s = db.pg_schema()
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in s and " REAL" not in s


def test_insert_returns_id_and_upsert():
    a = db.x("INSERT INTO channels(name,url) VALUES ('a','json://x')")
    b = db.x("INSERT INTO channels(name,url) VALUES ('b','json://y')")
    assert a and b and a != b
    db.x("INSERT INTO channels(name,url) VALUES ('a','json://z') ON CONFLICT(name) DO UPDATE SET url=excluded.url")
    assert db.q1("SELECT url FROM channels WHERE name='a'")["url"] == "json://z"
    assert db.q1("SELECT COUNT(*) n FROM channels WHERE name LIKE 'A'")["n"] == (1 if db.is_postgres() else 1)
